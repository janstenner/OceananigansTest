    PlotlyJS.savefig(plot_handle, output; width = 1450, height = 1750)
    return output
end

function finite_text(value; digits = 4)
    value === missing && return "NA"
    isfinite(value) || return "not reached"
    return @sprintf("%.*g", digits, value)
end

function role_metric(metrics, protocol, role)
    selected = filter(row -> row.protocol === protocol && row.role == role, metrics.terminal)
    return isempty(selected) ? nothing : only(selected)
end

function candidate_metric(data, role)
    haskey(data.candidates, role) || return nothing
    candidate = data.candidates[role]
    return (groups = Int(candidate[:active_groups]), mse = Float64(candidate[:validation_matching]))
end

function summary_table_rows(data_by_protocol, metrics)
    rows = NamedTuple[]
    for protocol in PROTOCOLS
        retention = only(filter(row -> row.protocol === protocol, metrics.retention))
        match = candidate_metric(data_by_protocol[protocol], "C_match")
        sparse = candidate_metric(data_by_protocol[protocol], "C_sparse")
        expert_test = role_metric(metrics, protocol, "expert")
        match_test = role_metric(metrics, protocol, "C_match")
        sparse_test = role_metric(metrics, protocol, "C_sparse")
        push!(rows, (;
            protocol = PROTOCOL_NAMES[protocol],
            go_combined_retention = "$(retention.go_retained)/$(retention.go_front_points)",
            gr_combined_retention = "$(retention.gr_retained)/$(retention.gr_front_points)",
            c_match_groups = match.groups,
            c_match_validation_mse = match.mse,
            c_sparse_groups = isnothing(sparse) ? missing : sparse.groups,
            c_sparse_validation_mse = isnothing(sparse) ? missing : sparse.mse,
            expert_test_mean_nu = expert_test.mean_nu,
            c_match_test_mean_nu = match_test.mean_nu,
            c_sparse_test_mean_nu = isnothing(sparse_test) ? missing : sparse_test.mean_nu,
        ))
    end
    return rows
end

function write_summary_table(output_dir, rows)
    csv_path = write_csv(joinpath(output_dir, "table_1_summary.csv"), rows)
    markdown_path = joinpath(output_dir, "table_1_summary.md")
    open(markdown_path, "w") do io
        println(io, "# Package 6 summary table\n")
        println(io, "| Protocol | GO retained | GR retained | C_match (groups, validation MSE) | C_sparse (groups, validation MSE) | Expert test mean Nu | C_match test mean Nu | C_sparse test mean Nu |")
        println(io, "|---|---:|---:|---:|---:|---:|---:|---:|")
        for row in rows
            match = "$(row.c_match_groups), $(@sprintf("%.3e", row.c_match_validation_mse))"
            sparse = row.c_sparse_groups === missing ? "NA" : "$(row.c_sparse_groups), $(@sprintf("%.3e", row.c_sparse_validation_mse))"
            sparse_nu = row.c_sparse_test_mean_nu === missing ? "NA" : @sprintf("%.5f", row.c_sparse_test_mean_nu)
            @printf(io, "| %s | %s | %s | %s | %s | %.5f | %.5f | %s |\n",
                row.protocol, row.go_combined_retention, row.gr_combined_retention,
                match, sparse, row.expert_test_mean_nu, row.c_match_test_mean_nu, sparse_nu)
        end
        println(io, "\n`Retained` means retained after pooling the GO and GR method fronts into one combined nondominated front. Test mean Nu is computed with `state_Nu` and lower is better.")
    end
    return (; csv_path, markdown_path)
end

function write_metric_csvs(output_dir, metrics)
    write_csv(joinpath(output_dir, "strength_sparsity_response.csv"), reduce(vcat, [metrics.responses[p].rows for p in PROTOCOLS]))
    write_csv(joinpath(output_dir, "strength_spearman.csv"), reduce(vcat, [metrics.responses[p].trends for p in PROTOCOLS]))
    write_csv(joinpath(output_dir, "quality_constrained_hitting_runs.csv"), reduce(vcat, [metrics.quality_hitting[p].run_rows for p in PROTOCOLS]))
    write_csv(joinpath(output_dir, "quality_constrained_hitting_summary.csv"), reduce(vcat, [metrics.quality_hitting[p].summary_rows for p in PROTOCOLS]))
    write_csv(joinpath(output_dir, "attainment_summary.csv"), metrics.attainment)
    write_csv(joinpath(output_dir, "combined_front_retention.csv"), metrics.retention)
    write_csv(joinpath(output_dir, "terminal_test_summary.csv"), metrics.terminal)
    return nothing
end

function write_metrics_report(output_dir, data_by_protocol, metrics)
    path = joinpath(output_dir, "paper_metrics.md")
    open(path, "w") do io
        println(io, "# Package 6 paper metrics\n")
        println(io, "This report is generated deterministically from the completed Package-6 analysis products. Fixed IC uses the quality threshold `MSE <= $(QUALITY_THRESHOLDS[:fixed])`; Varying IC uses `MSE <= $(QUALITY_THRESHOLDS[:varying])`. No training, validation, candidate selection, or rollout is performed by the paper-figure script.\n")

        println(io, "## 1. Empirical attainment across seeds\n")
        println(io, "`1/3`, `2/3`, and `3/3` are the best validation-MSE envelopes attained by at least one, two, or all three paired replicates at group budget `B`. The log spread is `log(L_3/3 / L_1/3)`; smaller finite values mean less seed sensitivity.\n")
        println(io, "| Protocol | Method | B | 1/3 MSE | 2/3 MSE | 3/3 MSE | Log spread |")
        println(io, "|---|---|---:|---:|---:|---:|---:|")
