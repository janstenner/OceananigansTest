function step_value(rows, update)
    selected = filter(item -> int_value(item, :update) <= update, rows)
    isempty(selected) && return float_value(first(sort(rows; by = item -> int_value(item, :update))), :coverage)
    return float_value(last(sort(selected; by = item -> int_value(item, :update))), :coverage)
end

function archive_series(data, method, strength_index, grid)
    matching = [item for item in data.archive if string_value(item, :method) == method && int_value(item, :strength_index) == strength_index]
    run_ids = sort(unique(string_value(item, :run_id) for item in matching))
    length(run_ids) == 3 || error("Expected three archive runs for $(data.protocol), $method s$strength_index.")
    budget = P6_UPDATES[data.protocol]
    matrix = zeros(Float64, length(run_ids), length(grid))
    for (run_index, run_id) in enumerate(run_ids)
        rows = [item for item in matching if string_value(item, :run_id) == run_id]
        for (grid_index, progress) in enumerate(grid)
            matrix[run_index, grid_index] = step_value(rows, round(Int, progress * budget))
        end
    end
    return (;
        low = vec(minimum(matrix; dims = 1)),
        median = [median(view(matrix, :, index)) for index in axes(matrix, 2)],
        high = vec(maximum(matrix; dims = 1)),
    )
end

