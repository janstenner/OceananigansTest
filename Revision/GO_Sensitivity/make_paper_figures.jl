        println(io, "For each strength and paired replicate, the response is the sparsest run-front point satisfying the protocol-specific quality threshold. `NR` means that the run never placed a point below that threshold in its Pareto archive. Spearman rho correlates the ranks of strength and active-group count over qualifying strengths only. `rho = -1` is a perfectly monotone decrease; magnitude, spacing, and MSE are not encoded. All current correlations use the complete five-strength grid.\n")
        println(io, "| Protocol | Replicate | Qualifying strengths | Spearman rho |")
        println(io, "|---|---:|---:|---:|")
        for protocol in PROTOCOLS, row in metrics.responses[protocol].trends
            @printf(io, "| %s | %d | %d/5 | %s |\n", PROTOCOL_NAMES[protocol], row.replicate, row.qualified_strengths, finite_text(row.spearman_rho))
        end
        println(io, "\nExact strength-by-seed values are in [`strength_sparsity_response.csv`](strength_sparsity_response.csv).\n")

        println(io, "## 3. Quality-constrained sparsification speed and reachability\n")
        println(io, "`T_(B,eps)` is the first update with no more than `B` active groups and validation MSE below the protocol threshold. Median normalized time is reported only among successful seeds and must be read together with reachability `k/3`.\n")
        println(io, "| Protocol | Strength | B | Reachability | Median T/Tmax | Successful-seed range |")
        println(io, "|---|---:|---:|---:|---:|---:|")
