function validate_status(path, protocol)
    isfile(path) || error("Analysis status is missing: $path")
    loaded = JLD2.load(path)
    Symbol(loaded["state"]) === :complete || error("$(PROTOCOL_NAMES[protocol]) analysis is not complete.")
    Symbol(loaded["protocol"]) === protocol || error("Protocol mismatch in $path.")
    Int(loaded["training_run_count"]) == 18 || error("Expected 18 training runs in $path.")
    return loaded
end

function load_candidates(path, protocol)
    isfile(path) || error("Candidate manifest is missing: $path")
    loaded = JLD2.load(path)
    Symbol(loaded["protocol"]) === protocol || error("Candidate protocol mismatch in $path.")
    loaded["selection_uses_test_data"] == false || error("Candidate selection unexpectedly used test data.")
    loaded["frozen_before_test"] == true || error("Candidate manifest was not frozen before testing.")
    candidates = Dict{String, Dict{Symbol, Any}}()
    for raw in loaded["candidates"]
        candidate = Dict{Symbol, Any}(Symbol(key) => value for (key, value) in raw)
        candidates[string(candidate[:selection_role])] = candidate
    end
    haskey(candidates, "C_match") || error("$protocol has no C_match candidate.")
    return candidates
end

function load_protocol(results_dir, protocol)
    paths = required_paths(results_dir, protocol)
    for path in values(paths)
        isfile(path) || error("Required Package-6 artifact is missing: $path")
    end
    status = validate_status(paths[:status], protocol)
    candidates = load_candidates(paths[:candidates], protocol)
    return (;
        protocol,
        paths,
        status,
        candidates,
        checkpoints = read_csv(paths[:checkpoints]),
        fronts = read_csv(paths[:fronts]),
        attainment = read_csv(paths[:attainment]),
        hitting = read_csv(paths[:hitting]),
        resets = read_csv(paths[:resets]),
        archive = read_csv(paths[:archive]),
        test_episodes = read_csv(paths[:test_episodes]),
        test_returns = read_csv(paths[:test_returns]),
    )
end

function validate_loaded_data(data)
    go_runs = unique(string_value(row, :run_id) for row in data.checkpoints if string_value(row, :method) == "go")
    gr_runs = unique(string_value(row, :run_id) for row in data.checkpoints if string_value(row, :method) == "gr")
    length(go_runs) == 15 || error("$(data.protocol): expected 15 GO runs, found $(length(go_runs)).")
    length(gr_runs) == 3 || error("$(data.protocol): expected 3 GR runs, found $(length(gr_runs)).")
    strengths = sort(unique(float_value(row, :regularization_strength) for row in data.checkpoints if string_value(row, :method) == "go"))
    strengths == sort(collect(P6_STRENGTHS[data.protocol])) || error("$(data.protocol): GO strength grid differs from Package6Study.jl.")
    roles = Set(string_value(row, :role) for row in data.test_episodes)
    "expert" in roles || error("$(data.protocol): expert test episodes are missing.")
    "C_match" in roles || error("$(data.protocol): C_match test episodes are missing.")
    all(haskey(row, :global_nusselt) for row in data.test_episodes) || error("$(data.protocol): state_Nu test values are missing.")
    return nothing
end

function response_metrics(data)
    threshold = QUALITY_THRESHOLDS[data.protocol]
    rows = NamedTuple[]
    for replicate in P6_REPLICATES, (strength_index, strength) in enumerate(P6_STRENGTHS[data.protocol])
        matching = [row for row in data.fronts if
            string_value(row, :front_scope) == "run" &&
            string_value(row, :method) == "go" &&
            int_value(row, :replicate) == replicate &&
            int_value(row, :strength_index) == strength_index &&
            float_value(row, :validation_matching) <= threshold]
        if isempty(matching)
            push!(rows, (;
                protocol = data.protocol, replicate, strength_index,
                strength = Float64(strength), threshold, reached = false,
                active_groups = missing, validation_mse = missing, update = missing,
            ))
        else
            best = first(sort(matching; by = row -> (
                int_value(row, :active_groups),
                float_value(row, :validation_matching),
                int_value(row, :update),
                string_value(row, :run_id),
            )))
            push!(rows, (;
                protocol = data.protocol, replicate, strength_index,
                strength = Float64(strength), threshold, reached = true,
                active_groups = int_value(best, :active_groups),
                validation_mse = float_value(best, :validation_matching),
                update = int_value(best, :update),
            ))
        end
    end
    trends = NamedTuple[]
    for replicate in P6_REPLICATES
        selected = sort(filter(row -> row.replicate == replicate && row.reached, rows); by = row -> row.strength)
        rho = spearman_correlation([row.strength for row in selected], [row.active_groups for row in selected])
        push!(trends, (;
            protocol = data.protocol, replicate, threshold,
            qualified_strengths = length(selected), spearman_rho = rho,
        ))
    end
    return (; rows, trends)
end

function quality_hitting_metrics(data)
    threshold = QUALITY_THRESHOLDS[data.protocol]
    budget = P6_UPDATES[data.protocol]
    run_rows = NamedTuple[]
    for replicate in P6_REPLICATES, (strength_index, strength) in enumerate(P6_STRENGTHS[data.protocol]), target in QUALITY_TARGETS
        matching = [row for row in data.checkpoints if
            string_value(row, :method) == "go" &&
            int_value(row, :replicate) == replicate &&
            int_value(row, :strength_index) == strength_index &&
            int_value(row, :active_groups) <= target &&
            float_value(row, :validation_matching) <= threshold]
        if isempty(matching)
            push!(run_rows, (;
                protocol = data.protocol, replicate, strength_index,
                strength = Float64(strength), target_groups = target, threshold,
                reached = false, first_update = missing, normalized_first_update = missing,
                validation_mse_at_hit = missing,
            ))
        else
            hit = first(sort(matching; by = row -> int_value(row, :update)))
            update = int_value(hit, :update)
            push!(run_rows, (;
                protocol = data.protocol, replicate, strength_index,
                strength = Float64(strength), target_groups = target, threshold,
                reached = true, first_update = update, normalized_first_update = update / budget,
                validation_mse_at_hit = float_value(hit, :validation_matching),
            ))
        end
    end
    summary_rows = NamedTuple[]
    for (strength_index, strength) in enumerate(P6_STRENGTHS[data.protocol]), target in QUALITY_TARGETS
        selected = filter(row -> row.strength_index == strength_index && row.target_groups == target, run_rows)
        reached = filter(row -> row.reached, selected)
        normalized = Float64[row.normalized_first_update for row in reached]
        push!(summary_rows, (;
            protocol = data.protocol, strength_index, strength = Float64(strength),
            target_groups = target, threshold,
            reached_seeds = length(reached), seed_count = length(selected),
            reachability_rate = length(reached) / length(selected),
            median_normalized_first_update = isempty(normalized) ? missing : median(normalized),
            minimum_normalized_first_update = isempty(normalized) ? missing : minimum(normalized),
            maximum_normalized_first_update = isempty(normalized) ? missing : maximum(normalized),
        ))
    end
    return (; run_rows, summary_rows)
end

function attainment_metrics(data)
    rows = NamedTuple[]
    for method in ("go", "gr"), target in QUALITY_TARGETS
        values = Dict{Int, Float64}()
        for required in 1:3
            matching = [row for row in data.attainment if
                string_value(row, :method) == method &&
                int_value(row, :active_groups) == target &&
                int_value(row, :attained_seeds) == required]
            length(matching) == 1 || error("Missing $method attainment at B=$target for $(data.protocol).")
            values[required] = float_value(only(matching), :validation_mse)
        end
        delta = isfinite(values[1]) && isfinite(values[3]) ? log(values[3] / values[1]) : Inf
        push!(rows, (;
            protocol = data.protocol, method, target_groups = target,
            mse_1_of_3 = values[1], mse_2_of_3 = values[2], mse_3_of_3 = values[3],
            log_attainment_spread = delta,
        ))
    end
    return rows
end

function normalized_front_rows(data, method)
    return [Dict{Symbol, Any}(
        :active_groups => int_value(row, :active_groups),
        :validation_matching => float_value(row, :validation_matching),
        :update => int_value(row, :update),
        :run_id => string_value(row, :run_id),
        :candidate_id => string_value(row, :candidate_id),
        :method => Symbol(method),
        :numeric_status => :ok,
    ) for row in data.fronts if
        string_value(row, :front_scope) == "global_method" &&
        string_value(row, :method) == method]
end

function combined_retention_metrics(data)
    go = normalized_front_rows(data, "go")
    gr = normalized_front_rows(data, "gr")
    combined = scientific_front(vcat(go, gr))
    retained = Set(string(record[:candidate_id]) for record in combined)
    return (;
        protocol = data.protocol,
        go_front_points = length(go),
        go_retained = count(record -> string(record[:candidate_id]) in retained, go),
        gr_front_points = length(gr),
        gr_retained = count(record -> string(record[:candidate_id]) in retained, gr),
        combined_front_points = length(combined),
    )
end

function terminal_metrics(data)
    rows = NamedTuple[]
    for role in CONTROLLER_ORDER
        selected = filter(row -> string_value(row, :role) == role, data.test_episodes)
        isempty(selected) && continue
        nusselt = float_value.(selected, Ref(:global_nusselt))
        cases = unique(string_value(row, :case) for row in selected)
        per_case_nu = Float64[]
        for case in cases
            case_nusselt = [float_value(row, :global_nusselt) for row in selected if string_value(row, :case) == case]
            push!(per_case_nu, mean(case_nusselt))
        end
        returns = [float_value(row, :return) for row in data.test_returns if string_value(row, :role) == role]
        push!(rows, (;
            protocol = data.protocol, role, cases = length(cases),
            mean_nu = mean(nusselt), median_case_nu = median(per_case_nu),
            minimum_case_nu = minimum(per_case_nu), maximum_case_nu = maximum(per_case_nu),
            mean_200_step_return = mean(returns),
        ))
    end
    return rows
end

function calculate_metrics(data_by_protocol)
    responses = Dict(protocol => response_metrics(data_by_protocol[protocol]) for protocol in PROTOCOLS)
    quality_hitting = Dict(protocol => quality_hitting_metrics(data_by_protocol[protocol]) for protocol in PROTOCOLS)
    attainment = reduce(vcat, [attainment_metrics(data_by_protocol[protocol]) for protocol in PROTOCOLS])
    retention = [combined_retention_metrics(data_by_protocol[protocol]) for protocol in PROTOCOLS]
    terminal = reduce(vcat, [terminal_metrics(data_by_protocol[protocol]) for protocol in PROTOCOLS])
    return (; responses, quality_hitting, attainment, retention, terminal)
end

function rgba(hex::AbstractString, alpha::Real)
    value = replace(hex, "#" => "")
    length(value) == 6 || error("Expected six-digit hex color, got $hex.")
    red = parse(Int, value[1:2]; base = 16)
    green = parse(Int, value[3:4]; base = 16)
    blue = parse(Int, value[5:6]; base = 16)
    return "rgba($red,$green,$blue,$alpha)"
end

function paper_axis(title; log = false, reversed = false, range = nothing, kwargs...)
    fields = Dict{Symbol, Any}(
        :title => attr(text = title, standoff = 10),
        :showline => true,
        :mirror => true,
        :linecolor => "#3A3A3A",
        :linewidth => 1,
        :ticks => "outside",
        :gridcolor => GRID_COLOR,
        :zeroline => false,
        :type => log ? "log" : "linear",
    )
    reversed && (fields[:autorange] = "reversed")
    !isnothing(range) && (fields[:range] = range)
    for (key, value) in kwargs
        fields[key] = value
    end
    return attr(; fields...)
end

