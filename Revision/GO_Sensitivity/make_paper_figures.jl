function usage(io::IO = stdout)
    println(io, """
    Usage:
      julia --startup-file=no --project=. Revision/GO_Sensitivity/make_paper_figures.jl [options]

    Options:
      --results-dir DIR  Package-6 study root (default: Revision/GO_Sensitivity/results/study).
      --output-dir DIR   Output directory (default: <results-dir>/paper).
      --check-only       Validate inputs and calculate metrics without exporting figures.
      --self-test        Run deterministic tests that require no study results.
      --help             Show this message.

    The script consumes the fixed and varying analysis products generated by
    analyze_study_worker.jl. It never starts training, validation, or test rollouts.
    """)
