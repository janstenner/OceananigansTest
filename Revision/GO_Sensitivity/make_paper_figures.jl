function sha256_file(path)
    open(path, "r") do io
        return bytes2hex(SHA.sha256(io))
    end
end

function write_provenance(output_dir, data_by_protocol)
    inputs = String[]
    for protocol in PROTOCOLS
        append!(inputs, collect(values(data_by_protocol[protocol].paths)))
    end
    sort!(unique!(inputs))
    path = joinpath(output_dir, "provenance.sha256")
    open(path, "w") do io
        println(io, "# Package 6 paper-output input manifest")
        println(io, "# Script: $(abspath(@__FILE__))")
        println(io, "# Script SHA-256: $(sha256_file(abspath(@__FILE__)))")
        for input in inputs
            relative = relpath(input, dirname(output_dir))
            println(io, "$(sha256_file(input))  $(replace(relative, '\\' => '/'))")
        end
    end
    return path
end

function run_self_tests()
    @assert split_csv_line("a,b,c") == ["a", "b", "c"]
    @assert split_csv_line("a,\"b,c\",\"d\"\"e\"") == ["a", "b,c", "d\"e"]
    @assert spearman_correlation([1, 2, 3], [3, 2, 1]) == -1.0
    records = [
        Dict(:active_groups => 1, :validation_matching => 2.0, :update => 1, :numeric_status => :ok),
        Dict(:active_groups => 2, :validation_matching => 1.0, :update => 2, :numeric_status => :ok),
        Dict(:active_groups => 3, :validation_matching => 3.0, :update => 3, :numeric_status => :ok),
    ]
    @assert length(scientific_front(records)) == 2
    @assert rgba("#277DA1", 0.5) == "rgba(39,125,161,0.5)"
    @assert length(EVALUATION_STRENGTH_COLORS) == 5
    @assert last(EVALUATION_STRENGTH_COLORS) == GR_COLOR
    println("Package-6 paper figure self-tests passed.")
    return nothing
end

function main(arguments = ARGS)
    options = parse_arguments(arguments)
    isnothing(options) && return nothing
    if options.self_test
        run_self_tests()
        return nothing
    end

    data_by_protocol = Dict(protocol => load_protocol(options.results_dir, protocol) for protocol in PROTOCOLS)
    foreach(validate_loaded_data, values(data_by_protocol))
    metrics = calculate_metrics(data_by_protocol)

    if options.check_only
        for protocol in PROTOCOLS
            response = metrics.responses[protocol]
            retention = only(filter(row -> row.protocol === protocol, metrics.retention))
            println("$(PROTOCOL_NAMES[protocol]): inputs valid; qualifying strength points = $(count(row -> row.reached, response.rows))/15; combined retention GO $(retention.go_retained)/$(retention.go_front_points), GR $(retention.gr_retained)/$(retention.gr_front_points).")
        end
        return nothing
    end

    mkpath(options.output_dir)
    write_metric_csvs(options.output_dir, metrics)
    table_rows = summary_table_rows(data_by_protocol, metrics)
    table_paths = write_summary_table(options.output_dir, table_rows)
    report_path = write_metrics_report(options.output_dir, data_by_protocol, metrics)
    provenance_path = write_provenance(options.output_dir, data_by_protocol)

    main_figure = make_main_figure(data_by_protocol, metrics, joinpath(options.output_dir, "figure_1_main.svg"))
    terminal_figure = make_terminal_figure(data_by_protocol, joinpath(options.output_dir, "figure_2_terminal_test.svg"))
    supplement_figure = make_supplement_figure(data_by_protocol, joinpath(options.output_dir, "figure_s1_stability_diagnostics.svg"))
    evaluation_figure = make_all_evaluations_pareto_figure(data_by_protocol, joinpath(options.output_dir, "figure_s2_all_evaluations_pareto.svg"))

    println("Package-6 paper outputs written to $(options.output_dir):")
    for path in (main_figure, terminal_figure, supplement_figure, evaluation_figure, table_paths.markdown_path, report_path, provenance_path)
        println("  $(path)")
    end
    return nothing
end

