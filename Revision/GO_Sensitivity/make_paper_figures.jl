function parse_arguments(arguments)
    values = Dict{String, Any}(
        "results_dir" => joinpath(@__DIR__, "results", "study"),
        "output_dir" => nothing,
        "check_only" => false,
        "self_test" => false,
    )
    index = 1
    while index <= length(arguments)
        argument = arguments[index]
        if argument == "--help"
            usage()
            return nothing
        elseif argument == "--check-only"
            values["check_only"] = true
            index += 1
        elseif argument == "--self-test"
            values["self_test"] = true
            index += 1
        elseif argument in ("--results-dir", "--output-dir")
            index < length(arguments) || error("Missing value after $argument.")
            values[replace(argument[3:end], '-' => '_')] = arguments[index + 1]
            index += 2
        else
            error("Unknown argument '$argument'. Use --help for usage.")
        end
    end
    results_dir = abspath(string(values["results_dir"]))
    output_dir = isnothing(values["output_dir"]) ? joinpath(results_dir, "paper") : abspath(string(values["output_dir"]))
    return (;
        results_dir,
        output_dir,
        check_only = Bool(values["check_only"]),
        self_test = Bool(values["self_test"]),
    )
end

function split_csv_line(line::AbstractString)
    fields = String[]
    buffer = IOBuffer()
    quoted = false
    index = firstindex(line)
    while index <= lastindex(line)
        character = line[index]
        if character == '"'
            next_index = nextind(line, index)
            if quoted && next_index <= lastindex(line) && line[next_index] == '"'
                write(buffer, '"')
                index = nextind(line, next_index)
                continue
            end
            quoted = !quoted
        elseif character == ',' && !quoted
            push!(fields, String(take!(buffer)))
        else
            write(buffer, character)
        end
        index = nextind(line, index)
    end
    quoted && error("Unterminated quoted CSV field.")
    push!(fields, String(take!(buffer)))
    return fields
end

function read_csv(path::AbstractString)
    isfile(path) || error("Required CSV is missing: $path")
    lines = readlines(path)
    isempty(lines) && error("CSV is empty: $path")
    headers = Symbol.(split_csv_line(chomp(lines[1])))
    rows = Dict{Symbol, String}[]
    for (offset, line) in enumerate(lines[2:end])
        line_number = offset + 1
        isempty(strip(line)) && continue
        values = split_csv_line(chomp(line))
        length(values) == length(headers) || error("CSV column mismatch in $path at line $line_number.")
        push!(rows, Dict(headers[index] => values[index] for index in eachindex(headers)))
    end
    return rows
end

string_value(row, key::Symbol) = row[key]
int_value(row, key::Symbol) = parse(Int, row[key])
float_value(row, key::Symbol) = parse(Float64, row[key])
symbol_value(row, key::Symbol) = Symbol(row[key])

function optional_float(row, key::Symbol)
    value = strip(row[key])
    isempty(value) && return missing
    return parse(Float64, value)
end

function csv_escape(value)
    value === missing && return ""
    text = string(value)
    occursin(r"[\",\n\r]", text) || return text
    return "\"" * replace(text, "\"" => "\"\"") * "\""
end

function write_csv(path, rows)
    rows = collect(rows)
    mkpath(dirname(path))
    keys_order = isempty(rows) ? Symbol[] : sort!(unique(vcat([collect(keys(row)) for row in rows]...)); by = string)
    open(path, "w") do io
        println(io, join(string.(keys_order), ','))
        for row in rows
            println(io, join((csv_escape(haskey(row, key) ? row[key] : missing) for key in keys_order), ','))
        end
    end
    return path
end

