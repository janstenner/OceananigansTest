function save_study_summary!(manager, job, result, elapsed_seconds)
    return pareto_atomic_save(
        joinpath(manager.run_directory, "summary.jld2");
        schema_version = P6_SCHEMA_VERSION,
        experiment = :package6_sc_go_sensitivity,
        completed_at = string(Dates.now()),
        run_id = job.id,
        protocol = job.protocol,
        method = job.method,
        replicate = job.replicate,
        regularization_strength = job.regularization_strength,
        elapsed_seconds = Float64(elapsed_seconds),
        update_count = length(result.losses),
        final_training_loss = isempty(result.losses) ? NaN : last(result.losses),
        evaluation_count = manager.evaluation_count,
        pareto_front = manager.front,
        config_fingerprint = manager.config_fingerprint,
    )
end

function validate_complete_run_without_runtime(options, previous)
    job = options.job
    directory = run_directory(options.results_root, job)
    config_path = joinpath(directory, "config.jld2")
    summary_path = joinpath(directory, "summary.jld2")
    resume_path = joinpath(directory, "resume", "latest.jld2")
    all(isfile, (config_path, summary_path, resume_path)) || error(
        "Run $(job.id) is marked complete but is missing config, summary, or resume data.",
    )
    loaded_config = JLD2.load(config_path)
    config = Dict{Symbol, Any}(Symbol(key) => value for (key, value) in loaded_config["config"])
    config_fingerprint = string(loaded_config["config_fingerprint"])
    string(previous[:config_fingerprint]) == config_fingerprint || error("Complete status/config fingerprint mismatch.")
    expected_updates = isnothing(options.smoke_updates) ? job.updates : options.smoke_updates
    checks = (
        Symbol(config[:experiment]) === :package6_sc_go_sensitivity,
        Symbol(config[:protocol]) === job.protocol,
        Symbol(config[:method]) === job.method,
        Int(config[:replicate]) == job.replicate,
        Int(config[:strength_index]) == job.strength_index,
        Float64(config[:regularization_strength]) == job.regularization_strength,
        Int(config[:apprentice_seed]) == job.apprentice_seed,
        Int(config[:batch_order_seed]) == job.batch_seed,
        Int(config[:regularized_updates]) == expected_updates,
        Int(config[:evaluation_interval]) == P6_EVALUATION_INTERVAL,
        Float64(config[:regression_learning_rate]) == P6_REGRESSION_LEARNING_RATE,
        Int(config[:batch_size]) == P6_TRAINING_BATCH_SIZE[job.protocol],
        Int(config[:validation_batch_size]) == P6_VALIDATION_BATCH_SIZE[job.protocol],
        Bool(config[:group_channels]) == false,
        length(string(config[:initial_apprentice_parameter_hash])) == 64,
    )
    all(checks) || error("Complete run $(job.id) does not match the requested configuration.")
    if Bool(get(config, :slim_evaluation_records, false))
        isfile(joinpath(directory, "evaluations.jld2")) || error(
            "Complete compact run $(job.id) is missing evaluations.jld2.",
        )
        shard_directory = joinpath(directory, "evaluations")
        shards = isdir(shard_directory) ? filter(
            name -> startswith(name, "update_") && endswith(name, ".jld2"),
            readdir(shard_directory),
        ) : String[]
        isempty(shards) || error("Complete compact run $(job.id) still contains evaluation shards.")
    end
    summary = JLD2.load(summary_path)
    string(summary["config_fingerprint"]) == config_fingerprint || error("Complete summary/config fingerprint mismatch.")
    JLD2.jldopen(resume_path, "r") do resume
        string(resume["config_fingerprint"]) == config_fingerprint || error("Complete resume/config fingerprint mismatch.")
        Symbol(resume["status"]) === :complete || error("Complete run has a non-complete resume checkpoint.")
        Int(resume["update"]) == expected_updates || error("Complete resume checkpoint has the wrong final update.")
    end
    return directory
end

function run_loaded_study_worker(options, directory, expert_path)
    job = options.job
    Float64(learning_rate) == P6_REGRESSION_LEARNING_RATE || error(
        "Loaded regression learning rate $learning_rate does not match $P6_REGRESSION_LEARNING_RATE.",
    )
    coverages, datasets, corpus_identifier = assert_study_inputs(job.protocol, expert_path)
    initial_apprentice = deepcopy(apprentice)
    initial_hash = apprentice_parameter_hash(initial_apprentice)
    updates = isnothing(options.smoke_updates) ? job.updates : options.smoke_updates
    training_config = ApprenticeTrainingConfig(
        regularized_updates = updates,
        post_pruning_finetune_updates = 0,
        batch_size = P6_TRAINING_BATCH_SIZE[job.protocol],
        proximal_interval = 1,
        reweight_interval = 10,
        regularization_strength = job.regularization_strength,
        validation_batch_size = P6_VALIDATION_BATCH_SIZE[job.protocol],
        validation_prediction_mode = :autoregressive,
        diagnostic_teacher_forced = false,
    )
    schedule = CandidateSchedule(
        start_update = 0,
        evaluation_interval = P6_EVALUATION_INTERVAL,
        garbage_collection_interval = P6_GARBAGE_COLLECTION_INTERVAL,
        resume_interval = P6_RESUME_INTERVAL,
    )
    config = study_archive_config(
        job,
        updates,
        training_config,
        expert_path,
        corpus_identifier,
        datasets,
        initial_hash;
        smoke_test = !isnothing(options.smoke_updates),
    )
    manager = initialize_pareto_archive(directory; run_id = job.id, schedule, config)
    resume_checkpoint = load_resume_checkpoint(manager)
    if !isnothing(resume_checkpoint) && resume_checkpoint.status === :complete
        isfile(joinpath(directory, "summary.jld2")) || error("Complete run is missing summary.jld2.")
        compact_evaluations!(manager)
        write_status!(
            status_path(options.results_root, job);
            state = :complete,
            run_id = job.id,
            config_fingerprint = manager.config_fingerprint,
            update = resume_checkpoint.update,
            initial_apprentice_parameter_hash = initial_hash,
            skipped_complete = true,
        )
        println("Skipping complete run $(job.id).")
        return manager
    elseif !isnothing(resume_checkpoint) && resume_checkpoint.status === :failed && !options.retry_failed
        message = get(resume_checkpoint.resume_state, :failure_message, "unknown failure")
        error("Run $(job.id) is marked failed at update $(resume_checkpoint.update): $message. Use --retry-failed only after repairing the cause.")
    end
    resume = !isnothing(resume_checkpoint) && resume_checkpoint.status in (:running, :failed)
    write_status!(
        status_path(options.results_root, job);
        state = :running,
        run_id = job.id,
        protocol = job.protocol,
        method = job.method,
        replicate = job.replicate,
        strength_index = job.strength_index,
        regularization_strength = job.regularization_strength,
        update = isnothing(resume_checkpoint) ? 0 : resume_checkpoint.update,
        config_fingerprint = manager.config_fingerprint,
        initial_apprentice_parameter_hash = initial_hash,
        resumed = resume,
        started_at = string(Dates.now()),
    )

    println("Package 6 SC worker $(job.id)")
    println("  method/strength: $(job.method) / $(job.regularization_strength)")
    println("  replicate/seeds: $(job.replicate) / $(job.apprentice_seed), $(job.batch_seed)")
    println("  updates: $updates; validation interval: $P6_EVALUATION_INTERVAL")
    println("  corpus coverage: train=$(coverages[:train].actual), validation=$(coverages[:validation].actual), test=$(coverages[:test].actual) (unused)")
    println("  resume: $resume")
    println("  output: $directory")
    started = time()
    result = train_apprentice!(
        deepcopy(initial_apprentice);
        method = job.method,
        train_dataset = datasets[:train],
        validation_dataset = datasets[:validation],
        config = training_config,
        archive_manager = manager,
        threshold_specs = HardThresholdSpec[],
        group_rows_by_overlap = true,
        group_channels = false,
        training_rng = StableRNG(job.batch_seed),
        resume,
    )
    elapsed = time() - started
    summary = save_study_summary!(manager, job, result, elapsed)
    compact_evaluations!(manager)
    write_status!(
        status_path(options.results_root, job);
        state = :complete,
        run_id = job.id,
        protocol = job.protocol,
        method = job.method,
        replicate = job.replicate,
        strength_index = job.strength_index,
        regularization_strength = job.regularization_strength,
        update = updates,
        config_fingerprint = manager.config_fingerprint,
        initial_apprentice_parameter_hash = initial_hash,
        elapsed_seconds = elapsed,
        summary_path = summary,
        completed_at = string(Dates.now()),
    )
    @printf("Completed %s in %.2f seconds.\n", job.id, elapsed)
    return manager
end

function study_worker_main(arguments = ARGS)
    options = parse_worker_arguments(arguments)
    isnothing(options) && return nothing
    state_path = status_path(options.results_root, options.job)
    previous = load_status(state_path)
    if !isnothing(previous) && previous[:state] === :failed && !options.retry_failed
        error("Run $(options.job.id) is explicitly failed. Repair it and restart with --retry-failed.")
    end
    if !isnothing(previous) && previous[:state] === :complete
        try
            directory = validate_complete_run_without_runtime(options, previous)
            println("Skipping identity-checked complete run $(options.job.id): $directory")
            return directory
        catch error_value
            atomic_save(
                joinpath(run_directory(options.results_root, options.job), "failed_restart_attempt.jld2");
                schema_version = P6_SCHEMA_VERSION,
                state = :failed,
                run_id = options.job.id,
                error_type = string(typeof(error_value)),
                error_message = sprint(showerror, error_value),
                backtrace = sprint(Base.show_backtrace, catch_backtrace()),
                failed_at = string(Dates.now()),
            )
            rethrow()
        end
    end
    directory, expert_path = configure_worker_environment!(options)
    try
        include(joinpath(P6_DISTILLATION_DIRECTORY, "Expert_Apprentice.jl"))
        return Base.invokelatest(run_loaded_study_worker, options, directory, expert_path)
    catch error_value
        failure_entries = (
            run_id = options.job.id,
            protocol = options.job.protocol,
            method = options.job.method,
            replicate = options.job.replicate,
            strength_index = options.job.strength_index,
            regularization_strength = options.job.regularization_strength,
            error_type = string(typeof(error_value)),
            error_message = sprint(showerror, error_value),
            backtrace = sprint(Base.show_backtrace, catch_backtrace()),
            failed_at = string(Dates.now()),
        )
        if !isnothing(previous) && previous[:state] === :complete
            # A mismatched restart attempt must never destroy a valid complete
            # status. Preserve it and record the rejected attempt separately.
            atomic_save(
                joinpath(run_directory(options.results_root, options.job), "failed_restart_attempt.jld2");
                schema_version = P6_SCHEMA_VERSION,
                state = :failed,
                failure_entries...,
            )
        else
            write_status!(state_path; state = :failed, failure_entries...)
        end
        rethrow()
    end
end

if abspath(PROGRAM_FILE) == abspath(@__FILE__)
    try
        study_worker_main()
    catch error_value
        Base.display_error(stderr, error_value, catch_backtrace())
        exit(1)
    end
end
