const P6_DIRECTORY = @__DIR__
const P6_PROJECT_ROOT = normpath(joinpath(P6_DIRECTORY, "..", ".."))
const P6_DISTILLATION_DIRECTORY = joinpath(P6_PROJECT_ROOT, "Revision", "Expert_Apprentice_Distillation")
const P6_DEFAULT_RESULTS_ROOT = joinpath(P6_DIRECTORY, "results", "study")

function worker_usage(io::IO = stdout)
    println(io, """
    Package-6 SC sensitivity worker.

    Usage:
      julia --project=. run_study_worker.jl --protocol fixed|varying \\
        --method go|gr --strength-index N --replicate N [--results-dir PATH]
        [--retry-failed] [--smoke-updates N]

    For GR, --strength-index must be 0. --smoke-updates is test-only and is
    deliberately recorded in the configuration fingerprint.
    """)
end

function parse_worker_arguments(arguments)
    values = Dict{String, Any}(
        "protocol" => nothing,
        "method" => nothing,
        "strength_index" => nothing,
        "replicate" => nothing,
        "results_dir" => P6_DEFAULT_RESULTS_ROOT,
        "retry_failed" => false,
        "smoke_updates" => nothing,
    )
    index = 1
    while index <= length(arguments)
        argument = arguments[index]
        if argument == "--help"
            worker_usage()
            return nothing
        elseif argument == "--retry-failed"
            values["retry_failed"] = true
            index += 1
        elseif startswith(argument, "--")
            index == length(arguments) && error("Missing value after $argument.")
            key = replace(argument[3:end], "-" => "_")
            haskey(values, key) || error("Unknown option '$argument'.")
            values[key] = arguments[index + 1]
            index += 2
        else
            error("Unknown argument '$argument'.")
        end
    end
    for key in ("protocol", "method", "strength_index", "replicate")
        isnothing(values[key]) && error("--$(replace(key, "_" => "-")) is required.")
    end
    protocol = normalize_protocol(values["protocol"])
    method = Symbol(lowercase(string(values["method"])))
    method in (:go, :gr) || error("--method must be go or gr.")
    strength_index = parse(Int, string(values["strength_index"]))
    replicate = parse(Int, string(values["replicate"]))
    job = job_for(protocol, method, strength_index, replicate)
    smoke_updates = isnothing(values["smoke_updates"]) ? nothing : parse(Int, string(values["smoke_updates"]))
    !isnothing(smoke_updates) && smoke_updates < 0 && error("--smoke-updates must be nonnegative.")
    return (
        job,
        results_root = abspath(string(values["results_dir"])),
        retry_failed = Bool(values["retry_failed"]),
        smoke_updates,
    )
end

function configure_worker_environment!(options)
    job = options.job
    directory = run_directory(options.results_root, job)
    expert_path = joinpath(P6_DISTILLATION_DIRECTORY, "experts", string(job.protocol), "agent.jld2")
    ENV["DISTILLATION_PROTOCOL"] = string(job.protocol)
    ENV["DISTILLATION_AUTOLOAD_PROTOCOL"] = string(job.protocol)
    ENV["DISTILLATION_SKIP_AUTOLOAD"] = "false"
    ENV["DISTILLATION_GROUP_CHANNELS"] = "false"
    ENV["REVISION_RUN_SEED"] = string(job.apprentice_seed)
    ENV[job.protocol === :fixed ? "DISTILLATION_FIXED_EXPERT_PATH" : "DISTILLATION_VARYING_EXPERT_PATH"] = expert_path
    ENV["DISTILLATION_WORKER_DIRECTORY"] = joinpath(P6_DISTILLATION_DIRECTORY, "worker_results")
    ENV["DISTILLATION_ALLOW_FRESH_EXPERT"] = "false"
    ENV["REVISION_RUN_DIRECTORY"] = joinpath(directory, "runtime")
    ENV["DISTILLATION_OUTPUT_DIRECTORY"] = joinpath(directory, "apprentice_output")
    return (directory, expert_path)
end

function assert_study_inputs(protocol::Symbol, expert_path::AbstractString)
    isfile(expert_path) || error("Expert checkpoint is missing: $expert_path")
    coverages = Dict(split => distillation_coverage(protocol, split) for split in (:train, :validation, :test))
    for split in (:train, :validation, :test)
        coverage = coverages[split]
        coverage.complete || error(
            "Incomplete $protocol/$split distillation corpus: expected $(coverage.expected), found $(coverage.actual).",
        )
    end
    datasets = Dict(split => distillation_dataset(protocol, split) for split in (:train, :validation, :test))
    identifiers = Set(string(datasets[split][:expert_identifier]) for split in keys(datasets))
    length(identifiers) == 1 || error("$protocol corpus splits were generated by different experts: $identifiers")
    corpus_identifier = only(identifiers)
    loaded_identifier = string(DISTILLATION_EXPERT_METADATA[:identifier])
    corpus_identifier == loaded_identifier || error(
        "$protocol corpus expert $corpus_identifier does not match loaded expert $loaded_identifier.",
    )
    if protocol === :fixed
        datasets[:train] === datasets[:validation] === datasets[:test] || error(
            "Fixed IC must expose one shared train/validation/test dataset object.",
        )
    else
        length(Set(objectid(datasets[split]) for split in keys(datasets))) == 3 || error(
            "Varying IC requires distinct train, validation, and test dataset objects.",
        )
    end
    return (coverages, datasets, corpus_identifier)
end

function write_array_for_hash!(io::IO, values)
    array = Array(values)
    write(io, string(eltype(array)), UInt8(0), string(size(array)), UInt8(0))
    write(io, reinterpret(UInt8, vec(array)))
end

function apprentice_parameter_hash(model)
    io = IOBuffer()
    parameters = Flux.trainables(model)
    write(io, string(length(parameters)), UInt8(0))
    foreach(parameter -> write_array_for_hash!(io, parameter), parameters)
    return bytes2hex(SHA.sha256(take!(io)))
end

